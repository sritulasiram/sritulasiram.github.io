// Builds the loading placeholders for every photo in public/images/photography and writes them to
// src/data/photoPlaceholders.ts. Run it after adding or replacing a photo:
//
//   npm run photos:placeholders
//
// Each photo gets two things, both shown before the real image arrives:
//   color  the photo's average colour, which fills the tile at once
//   image  its ThumbHash (a ~25-byte summary of the photo's colours and light) decoded into a tiny, smooth
//          WebP, so the tile shows a soft blur of the photo from the first paint, with no JavaScript needed
//
// Uses sharp (installed with Next.js) and thumbhash (a dev dependency); neither is shipped to visitors.
import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";
import { rgbaToThumbHash, thumbHashToAverageRGBA, thumbHashToRGBA } from "thumbhash";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const PHOTO_DIR = path.join(ROOT, "public/images/photography");
const OUT = path.join(ROOT, "src/data/photoPlaceholders.ts");

const hex = (n) => Math.round(n * 255).toString(16).padStart(2, "0");

const files = (await readdir(PHOTO_DIR)).filter((f) => /\.jpe?g$/i.test(f)).sort();
const entries = [];
let total = 0;

for (const file of files) {
  // ThumbHash works on images of at most 100×100.
  const { data, info } = await sharp(path.join(PHOTO_DIR, file))
    .rotate()
    .resize(100, 100, { fit: "inside" })
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  const hash = rgbaToThumbHash(info.width, info.height, data);

  const avg = thumbHashToAverageRGBA(hash);
  const color = `#${hex(avg.r)}${hex(avg.g)}${hex(avg.b)}`;

  const decoded = thumbHashToRGBA(hash);
  const webp = await sharp(Buffer.from(decoded.rgba), { raw: { width: decoded.w, height: decoded.h, channels: 4 } })
    .removeAlpha()
    .webp({ quality: 60 })
    .toBuffer();
  const image = `data:image/webp;base64,${webp.toString("base64")}`;
  total += image.length;

  entries.push(`  "/images/photography/${file}": { color: "${color}", image: "${image}" },`);
}

const source = `// Generated by scripts/photo-placeholders.mjs. Do not edit by hand: run \`npm run photos:placeholders\`.
// Loading placeholders for each photo: its average colour and a tiny ThumbHash preview (see the script).

export interface PhotoPlaceholder {
  color: string;
  image: string;
}

export const PHOTO_PLACEHOLDERS: Record<string, PhotoPlaceholder> = {
${entries.join("\n")}
};
`;

await writeFile(OUT, source);
console.log(`Wrote ${entries.length} placeholders to ${path.relative(ROOT, OUT)} (${(total / 1024).toFixed(1)} KB of previews).`);
